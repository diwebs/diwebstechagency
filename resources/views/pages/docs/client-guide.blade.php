    <h2 class="text-xl font-bold text-brand-white mt-8 border-b border-brand-teal/10 pb-2">2. Reviewing and Signing Project Agreements</h2>
    <p class="text-sm text-[#94A3B8] leading-relaxed">
        Before development begins, we set up a milestone contract. This lists the phases of work, timelines, and costs.
    </p>
    <ul class="space-y-2 text-xs text-[#94A3B8] list-decimal pl-5">
        <li>In your Client Workspace, locate the active project under the <strong class="text-brand-white">Projects</strong> list.</li>
        <li>Click the project title to view its details.</li>
        <li>Read the agreement summary on the page.</li>
        <li>When you are satisfied with the terms, click the green <strong class="text-brand-cyan">"Sign Agreement"</strong> button. This records your digital authorization and alerts our engineering team to start coding!</li>
    </ul>

    <h2 class="text-xl font-bold text-brand-white mt-8 border-b border-brand-teal/10 pb-2">3. Uploading Assets & Project Files</h2>
    <p class="text-sm text-[#94A3B8] leading-relaxed">
        Do you need to share logo files, design wireframes, written copy, or server credentials? You can upload files directly to the project page:
    </p>
    <ul class="space-y-2 text-xs text-[#94A3B8] list-decimal pl-5">
        <li>Inside your active project view, scroll down to the <strong class="text-brand-white">Project Files</strong> section.</li>
        <li>Click <strong class="text-brand-white">"Browse Files"</strong> or drag and drop your file.</li>
        <li>Give the file a short description (e.g., "Company High-Res Logo") and click <strong class="text-brand-teal">"Upload"</strong>. Our team is automatically notified and can fetch the file instantly.</li>
    </ul>

