    <h2 class="text-xl font-bold text-brand-white mt-8 border-b border-brand-teal/10 pb-2">2. What is Zero-Trust Security?</h2>
    <p class="text-sm text-[#94A3B8] leading-relaxed">
        Traditional networks trust anyone who enters a password. In our <strong>Zero-Trust Model</strong>, we verify everything:
    </p>
    <ul class="space-y-2 text-xs text-[#94A3B8] list-disc pl-5">
        <li><strong>Role Isolation:</strong> Students can never access client invoices; clients can never view test answers. Access is locked down.</li>
        <li><strong>Encryption:</strong> All information traveling between your computer and our server is scrambled using TLS 1.3 encryption (indicated by the lock icon in your browser address bar).</li>
        <li><strong>Hardware Passkeys:</strong> We support biometrics (FaceID/Fingerprint) or device passcodes to log in. This completely blocks hackers from copying your password or sending phishing links.</li>
    </ul>

